def _rng() -> np.random.Generator:
    return np.random.default_rng(SEED)


# ── deterministic invented DEMONSTRATION history ─────────────────────────────
def demo_history_dataframe(n_rows: int = 168) -> pd.DataFrame:
    """Deterministic, clearly-invented demo history for illustrating the AI."""
    rng = _rng()
    years = np.linspace(2015, 2026, n_rows).round(0).astype(int)
    # inflation and fx move with Zimbabwe's (approximate, invented) story
    infl = np.where(years <= 2018, rng.uniform(3, 9, n_rows),
             np.where(years <= 2020, rng.uniform(15, 120, n_rows),
              np.where(years <= 2023, rng.uniform(100, 600, n_rows),
               rng.uniform(30, 90, n_rows))))
    fx = np.where(years <= 2018, rng.uniform(1.0, 2.0, n_rows),
           np.where(years <= 2020, rng.uniform(2, 25, n_rows),
            np.where(years <= 2023, rng.uniform(25, 600, n_rows),
             rng.uniform(30, 50, n_rows))))

    sectors = np.array(["Building", "Water & Sanitation", "Road",
                        "Telecommunications", "Agriculture",
                        "Transport / Logistics", "Industrial",
                        "Energy / Power"])
    sector_rng = rng.integers(0, len(sectors), n_rows)
    sector = sectors[sector_rng]
    sector_base = np.array([12.0, 17.0, 26.0, 21.0, 19.0, 24.0, 23.0, 32.0])
    base = sector_base[sector_rng]

    budget = np.power(10.0, rng.uniform(5.5, 8.3, n_rows))          # $0.3M-$200M
    complexity = np.clip(rng.normal(3.0, 0.9, n_rows) +
                         np.where(sector_rng == 7, 0.6, 0.0) +
                         np.where(sector_rng == 0, -0.7, 0.0), 1.0, 5.0).round(1)
    design = np.clip(96 - complexity * 4 - np.where(sector_rng == 7, 18, 0.0) -
                     6 * (complexity >= 4.0) - rng.normal(0, 14, n_rows),
                     25, 100).round(0)
    delay = np.clip(rng.poisson(18, n_rows) +
                    (complexity - 3) * 9 + np.where(sector_rng == 2, 12, 0.0) +
                    rng.normal(0, 15, n_rows), 0, 300).round(0)
    changes = np.clip(np.round(rng.exponential(2.4, n_rows) +
                               np.maximum(0, complexity - 2.5) * 1.2), 0, 12) \
        .astype(int)

    overrun = (base + 0.34 * (100 - design) - 13.0 +
               0.11 * delay + 1.5 * changes +
               1.4 * np.maximum(0, complexity - 3.5) ** 2 +
               0.055 * infl + 0.03 * fx + rng.normal(0, 7.5, n_rows))
    overrun = np.maximum(0.0, overrun * np.exp(rng.normal(0, 0.21, n_rows)))
    overrun = np.clip(overrun, 0, 250).round(1)

    names = [f"Demo Project {i+1:03d} ({sector[i]} {years[i]})"
             for i in range(n_rows)]
    return pd.DataFrame({
        "project": names,
        "year": years,
        "sector": sector,
        "budget_usd": budget.round(0),
        "duration_days": np.clip(120 + complexity * 80 +
                                 rng.normal(0, 60, n_rows), 90, 2000).round(0),
        "complexity": complexity,
        "design_completeness_pct": design,
        "procurement_delay_days": delay,
        "change_orders": changes,
        "inflation_at_award": infl.round(1),
        "fx_rate_at_award": fx.round(1),
        "actual_overrun_pct": overrun,
    })


