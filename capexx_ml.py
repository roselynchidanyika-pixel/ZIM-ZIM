def explain_calibration(metrics: Dict[str, Any]) -> str:
    cal = metrics["calibration"]
    max_gap = 0.0
    for a, b in zip(cal["fraction_positive"], cal["mean_predicted"]):
        max_gap = max(max_gap, abs(float(a) - float(b)))
    match = ("excellent" if max_gap < 0.08 else
             "reasonable" if max_gap < 0.18 else "weak")
    return f"""The calibration curve checks whether a "XX% risk" label means the
same thing in reality. Here the biggest gap between what the model predicted
and what actually happened was **{max_gap:.0%}** — {match}. When the model
says a project has 60% overrun risk, around 60% of similar projects truly did
overrun in the history it learned from."""


def explain_shapiro(res: Dict[str, Any]) -> str:
    p = res["pvalue"]
    normal = "yes — the bell-curve assumption holds" if p >= 0.05 else (
        "no — the data does NOT follow a bell curve")
    note = ("This is common in project finance: most projects stay near budget "
            "but a few blow up, creating a 'long tail'." if p < 0.05 else
            "We can use standard methods that assume a bell curve.")
    return (f"The **Shapiro-Wilk** test asks whether cost overruns follow a "
            f"bell curve. The p-value is **{p:.3f}** (test statistic "
            f"{res['statistic']:.3f}), which means {normal}. {note} "
            "(Skew: {:.2f}.)".format(res.get("skew", 0.0)))


def explain_breusch_pagan(res: Dict[str, Any]) -> str:
    p = res["pvalue"]
    if np.isnan(p):
        return res.get("note", "The test could not be run on this sample.")
    consistent = ("consistent" if p >= 0.05 else "NOT consistent")
    advice = ("You can trust predictions for small and large projects equally."
              if p >= 0.05 else
              "The model is less reliable for some project sizes — treat large "
              "and small-project predictions with extra caution.")
    return (f"The **Breusch-Pagan** test checks whether the model's errors are "
            f"roughly the same size for small and large projects. p-value "
            f"**{p:.2f}** (statistic {res['statistic']:.1f}, {res['df']} "
            f"degrees of freedom) → errors are {consistent}. {advice}")


def explain_durbin_watson(dw: float) -> str:
    if np.isnan(dw):
        return "Not enough residuals to compute the Durbin-Watson test."
    if 1.5 <= dw <= 2.5:
        verdict = "errors are random and independent — a good sign"
        advice = "one project's mistake does not predict the next one's."
    elif dw < 1.5:
        verdict = "errors trend in the same direction (positive correlation)"
        advice = "look for one shared cause behind the pattern."
    else:
        verdict = "errors alternate direction (negative correlation)"
        advice = "check whether corrections are over-shooting."
    return (f"The **Durbin-Watson** test looks for patterns in the model's "
            f"mistakes. The statistic is **{dw:.2f}**, and because values near "
            f"2.0 are ideal this means {verdict} — {advice}")


def explain_vif(vif: Dict[str, float]) -> str:
    rows = []
    any_high = False
    for k, v in vif.items():
        if not np.isnan(v):
            if v > 10:
                any_high = True
                verdict = "REDUNDANT — consider merging/removing"
            elif v >= 5:
                verdict = "some overlap — acceptable"
            else:
                verdict = "unique — good"
            rows.append(f"- **{k.replace('_', ' ')}**: VIF {v:.1f} — {verdict}")
    tail = ("The model uses many overlapping signals — watch collinearity."
            if any_high else
            "Each factor contributes something unique, so the model is "
            "stable and robust.")
    return ("The **VIF** test reveals whether two inputs are secretly measuring "
            "the same thing. Values under 5 are good; above 10 means redundancy:\n\n" +
            "\n".join(rows) + "\n\n" + tail)


